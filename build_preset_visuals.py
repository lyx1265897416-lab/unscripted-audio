def dur(f):
    return float(subprocess.run([FP, '-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', str(f)], capture_output=True, text=True).stdout.strip() or 0)


def cut(src, out, a, b, y):
    subprocess.run([FF, '-v', 'error', '-y', '-ss', f'{a:.2f}', '-to', f'{b:.2f}', '-i', str(src), '-an', '-vf',
                    f'crop=480:480:0:{y},scale={SIZE}:{SIZE},fps=24,setsar=1,format=yuv420p',
                    '-c:v', 'libx264', '-crf', '28', '-preset', 'veryfast', '-movflags', '+faststart', str(out)], check=True)


def build(sid):
    cfg = PRESET[sid]; od = ROOT / 'app' / 'v' / sid; od.mkdir(parents=True, exist_ok=True)
    s = open(cfg['data']).read(); d = json.loads(s[s.find('{'):s.rfind('}') + 1])
    clips, jobs = [], []
    for cid, src, a, b, cap, y in cfg['clips']:
        said = [c for c in d['CLIPS'][src]['cues'] if c.get('k') in ('dlg', 'her', 'vo') and c['s'] < b and c['e'] > a]
        line = ' / '.join(('她' if c['k'] == 'her' else '他') + '：' + c['zh'].replace('\n', '') for c in said)
        clips.append({'id': cid, 'kind': 'preset', 'cap': '预设完整版｜' + cap + (f'（台词：{line}）' if line else '')})
        jobs.append((Path(cfg['media']) / f'{src}.mp4', od / f'{cid}.mp4', a, b, y))

    def run(j):
        src, out, a, b, y = j
        if out.exists() and out.stat().st_size > 2000 and '--force' not in sys.argv: return
        try: cut(src, out, a, b, y)
        except Exception:
            out.unlink(missing_ok=True); raise
    with cf.ThreadPoolExecutor(6) as ex: list(ex.map(run, jobs))
    for c in clips:
        c['src'] = f'v/{sid}/{c["id"]}.mp4'; c['dur'] = round(dur(od / f"{c['id']}.mp4"), 2)
    vf = ROOT / 'data' / 'visuals' / f'{sid}.json'
    old = json.load(open(vf)) if vf.exists() else {'clips': [], 'pool': []}
    rest = [c for c in old['clips'] if c.get('kind') != 'preset']
    json.dump({'clips': clips + rest, 'pool': cfg['pool'], 'prefer': 'p', 'pool_old': old.get('pool_old') or old['pool']},
              open(vf, 'w'), ensure_ascii=False, indent=1)
    size = sum((od / f"{c['id']}.mp4").stat().st_size for c in clips)
    return sid, len(clips), 'preset clips', f'{size / 1e6:.1f}MB', len(rest), 'fallback clips'


if __name__ == '__main__':
    for sid in [a for a in sys.argv[1:] if not a.startswith('--')] or list(PRESET):
        print(build(sid), flush=True)
